"""기한 글자 → 날짜 환산 규칙 (design 1 의 표). 기준일 B = 2026-11-12(목)."""
from datetime import date, datetime

import pytest

from backend.duedate import base_date, kst_date, resolve

B = date(2026, 11, 12)  # 목요일


@pytest.mark.parametrize("text,expected", [
    ("오늘", "2026-11-12"), ("금일", "2026-11-12"), ("내일", "2026-11-13"), ("모레", "2026-11-14"), ("어제", "2026-11-11"),
    ("3일 뒤", "2026-11-15"), ("10일후", "2026-11-22"), ("2주 뒤", "2026-11-26"),
    ("다음 주", "2026-11-19"), ("다음 주까지", "2026-11-19"), ("차주", "2026-11-19"), ("지난 주", "2026-11-05"), ("지난 주까지", "2026-11-05"),
    ("금요일", "2026-11-13"), ("금요일까지", "2026-11-13"), ("금", "2026-11-13"), ("월요일", "2026-11-09"),
    ("이번 주 금요일", "2026-11-13"), ("이번 주 일요일", "2026-11-15"),
    ("다음 주 금요일", "2026-11-20"), ("다음주 월요일까지", "2026-11-16"), ("차주 화요일", "2026-11-17"),
    ("지난 주 금요일", "2026-11-06"),
    ("이번 달 말", "2026-11-30"), ("월말", "2026-11-30"), ("다음 달 말", "2026-12-31"),
    ("20일", "2026-11-20"), ("이번 달 25일까지", "2026-11-25"), ("다음 달 10일", "2026-12-10"),
    ("11월 30일", "2026-11-30"), ("1월 5일", "2027-01-05"), ("11/30", "2026-11-30"), ("3/1", "2027-03-01"),
    ("2026-12-01", "2026-12-01"), ("2027.1.15", "2027-01-15"),
    ("  다음 주   금요일 안에 ", "2026-11-20"), ("모레쯤", "2026-11-14"),
])
def test_resolves(text, expected):
    assert resolve(text, B) == date.fromisoformat(expected)


@pytest.mark.parametrize("text", ["", "   ", "미정", "이번 주", "이번 주 안", "이번 주 내", "지난 달", "다음 달", "곧", "ASAP",
                                  "2월 30일", "13월 1일", "32일"])
def test_unresolved_is_none(text):
    assert resolve(text, B) is None


def test_next_month_day_missing():
    assert resolve("다음 달 31일", date(2026, 10, 15)) is None  # 11월 31일 없음
    assert resolve("다음 달 말", date(2026, 12, 3)) == date(2027, 1, 31)  # 해 넘김


def test_monday_week_start():
    sunday = date(2026, 11, 15)
    assert resolve("월요일", sunday) == date(2026, 11, 9)  # 일요일도 그 주(월요일 시작)
    assert resolve("다음 주 월요일", sunday) == date(2026, 11, 16)


def test_kst_base_date():
    assert kst_date(datetime(2026, 11, 11, 23, 30)) == date(2026, 11, 12)  # UTC 23:30 = 한국 다음 날 08:30
    assert base_date(datetime(2026, 11, 1, 0, 0), datetime(2026, 11, 11, 23, 30)) == date(2026, 11, 12)  # 회의 날짜 우선
    assert base_date(datetime(2026, 11, 12, 16, 0), None) == date(2026, 11, 13)  # 직접 등록은 등록한 날
